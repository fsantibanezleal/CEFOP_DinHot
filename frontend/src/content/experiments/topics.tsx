export function FamilyTopic({ family }: { family: Family }) {
  return <DataView>{(b) => <FamilyBody family={family} cases={b.cases} index={b.index.cases} absent={b.absent} />}</DataView>;
}

function FamilyBody({
  family,
  cases,
  index,
  absent,
}: {
  family: Family;
  cases: CaseView[];
  index: { case_id: string; category: { en: string }; status: string }[];
  absent: { caseId: string; title: { en: string; es: string }; reason: { en: string; es: string } }[];
}) {
  const lang = useShellLang() as Lang;
  const ids = index.map((c) => c.case_id);
  const mine = index.filter((c) => c.category.en === CATEGORY[family]);
  const views = mine.map((c) => cases.find((x) => x.manifest.case_id === c.case_id)).filter((x): x is CaseView => !!x);
  return (
    <>
      <DocSection title={{ en: 'What this family asks', es: 'Qué pregunta esta familia' }} noRefsReason={NOREF('the questions are those of the case cards', 'las preguntas son las de las fichas de los casos')}>
        <p lang={lang}>{INTRO[family][lang]}</p>
      </DocSection>
      {mine.map((c) => {
        const v = cases.find((x) => x.manifest.case_id === c.case_id);
        if (v) return <CaseSection key={c.case_id} view={v} caseIds={ids} />;
        const a = absent.find((x) => x.caseId === c.case_id);
        return a ? <AbsentSection key={c.case_id} item={a} status={c.status} /> : null;
      })}
      {views.length > 0 && (
        <FamilyResults views={views} lang={lang}>
          {family === 'arrays' && (
            <>
              <h4 lang={lang}>{lang === 'es' ? 'El lazo de cámara' : 'The camera loop'}</h4>
              <FeedbackChart views={views} marks={PUBLISHED_FINALS} lang={lang} />
            </>
          )}
          {family === 'dynamics' && views.some((v) => v.trace.rearrangement) && (
            <>
              <h4 lang={lang}>{lang === 'es' ? 'La secuencia de reordenamiento' : 'The rearrangement sequence'}</h4>
              <FillingChart view={views.find((v) => v.trace.rearrangement) as CaseView} lang={lang} />
            </>
          )}
        </FamilyResults>
      )}
    </>
  );
}

