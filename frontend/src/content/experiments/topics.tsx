function CasesBody({ cases, index }: { cases: CaseView[]; index: { case_id: string; title: { en: string; es: string }; category: { en: string; es: string }; status: string; reason: { en: string; es: string } | null }[] }) {
  const f = useFmtObj(index.map((c) => c.case_id));
  const lang = f.lang;
  const es = lang === 'es';
  const baked = index.filter((c) => c.status === 'baked').length;
  const refused = index.filter((c) => c.status === 'refused').length;
  const synthetic = cases.length > 0 && cases.every((c) => c.manifest.real_or_synthetic === 'synthetic');
  const live = cases.flatMap((c) => Object.values(c.manifest.methods)).filter((m) => m.lane === 'live').length;
  const methods = cases.reduce((n, c) => n + Object.keys(c.manifest.methods).length, 0);
  const vals = {
    total: f.n(index.length, { decimals: 0 }),
    cats: f.n(new Set(index.map((c) => c.category.en)).size, { decimals: 0 }),
    baked: f.n(baked, { decimals: 0 }),
    refused: f.n(refused, { decimals: 0 }),
    synth: synthetic ? (es ? 'sintético' : 'synthetic') : es ? 'declarado en su manifiesto' : 'as its manifest declares',
    live: f.n(live, { decimals: 0 }),
    methods: f.n(methods, { decimals: 0 }),
  };
  const statusText = (s: string) => (s === 'baked' ? (es ? 'generado' : 'baked') : s === 'refused' ? (es ? 'rechazado' : 'refused') : s);
  return (
    <DocSection
      title={{ en: 'The cases and their data', es: 'Los casos y sus datos' }}
      area="datasets"
      noRefsReason={NOREF('the matrix is read from the case index and the manifests of the bake', 'la matriz se lee del índice de casos y de los manifiestos de la generación')}
    >
      <p lang={lang}>{fill(MATRIX.p1[lang], vals)}</p>
      <p lang={lang}>{fill(MATRIX.p2[lang], vals)}</p>
      <Scroll>
        <table className="caos-table" data-state="ready">
          <thead>
            <tr>
              <th className="caos-col-text">{es ? 'Caso' : 'Case'}</th>
              <th className="caos-col-text">{es ? 'Categoría' : 'Category'}</th>
              <th className="caos-col-text">{es ? 'Origen' : 'Origin'}</th>
              <th className="caos-col-text">{es ? 'Redistribución' : 'Redistribution'}</th>
              <th className="caos-col-text">{es ? 'Estado' : 'Status'}</th>
              <th className="caos-col-text">{es ? 'Carril' : 'Lane'}</th>
              <th>{es ? 'Métodos' : 'Methods'}</th>
              <th>{es ? 'Traza (KiB)' : 'Trace (KiB)'}</th>
              <th className="caos-col-text">{es ? 'Ancla publicada' : 'Published anchor'}</th>
            </tr>
          </thead>
          <tbody>
            {index.map((e) => {
              const c = cases.find((x) => x.manifest.case_id === e.case_id);
              const m = c?.manifest;
              return (
                <tr key={e.case_id}>
                  <td className="caos-col-text" style={WRAP}>{`${e.case_id.slice(0, 3)} ${e.title[lang]}`}</td>
                  <td className="caos-col-text" style={WRAP}>{e.category[lang]}</td>
                  <td className="caos-col-text">{m ? (m.real_or_synthetic === 'synthetic' ? (es ? 'sintético' : 'synthetic') : m.real_or_synthetic) : '-'}</td>
                  <td className="caos-col-text" style={{ ...WRAP, whiteSpace: 'normal' }}>
                    {m ? (m.real_or_synthetic === 'synthetic' ? (es ? 'generado por el pipeline, versionado con el producto' : 'generated by the pipeline, committed with the product') : '-') : '-'}
                  </td>
                  <td className="caos-col-text" style={WRAP}>{statusText(e.status)}</td>
                  <td className="caos-col-text">{m ? m.lane : '-'}</td>
                  <td>{m ? f.n(Object.keys(m.methods).length, { decimals: 0 }) : '-'}</td>
                  <td>{m ? f.n(m.artifact.bytes / 1024, { digits: 4 }) : '-'}</td>
                  <td className="caos-col-text" style={{ ...WRAP, whiteSpace: 'normal' }}>{m ? <span translate="no">{m.anchor.source[lang]}</span> : e.reason ? spanishDecimals(e.reason[lang], lang) : '-'}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </Scroll>
    </DocSection>
  );
}

