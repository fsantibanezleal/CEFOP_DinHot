// Generates src/lib/contract.gen.ts from ../docs/contracts/api.openapi.json (ADR-0080 decision 2: the schema files
// are the single source of every contract; the TypeScript types are generated, never hand-written).
// `--check` generates in memory and fails when the committed file differs, so a schema change without a
// regeneration stops `npm run build` (the currency check; no CI job of its own, ADR-0074).
//
// The OpenAPI document references the schema files; each file keeps its shared definitions in `$defs`, as a
// self-contained JSON Schema must. openapi-typescript would render `$defs` as a property of every document type,
// so the files are inlined here first: every `$defs` entry becomes a component and its `#/$defs/<name>` references
// point at it. A name defined twice must be defined identically (one type per name), or the generation fails.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '..', '..', 'docs', 'contracts');
const target = join(here, '..', 'src', 'lib', 'contract.gen.ts');
const HEADER = '// GENERATED by frontend/scripts/gen-contract-types.mjs from docs/contracts/api.openapi.json. Do not edit.\n';

const readJSON = (path) => JSON.parse(readFileSync(path, 'utf8'));

/** A copy of `node` with every `#/$defs/<name>` reference pointed at the component `<name>`. */
function relink(node) {
  if (Array.isArray(node)) return node.map(relink);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    out[key] = key === '$ref' && typeof value === 'string' && value.startsWith('#/$defs/')
      ? `#/components/schemas/${value.slice('#/$defs/'.length)}`
      : relink(value);
  }
  return out;
}

/** The OpenAPI document with every file reference of components.schemas inlined and its `$defs` hoisted. */
export function inlineDocument() {
  const doc = readJSON(join(contracts, 'api.openapi.json'));
  const schemas = doc.components.schemas;
  const hoisted = {};
  for (const [name, schema] of Object.entries(schemas)) {
    if (typeof schema.$ref !== 'string' || schema.$ref.startsWith('#')) continue;
    const { $defs = {}, $schema: _dialect, $id: _id, ...body } = readJSON(join(contracts, schema.$ref));
    for (const [defName, def] of Object.entries($defs)) {
      const linked = relink(def);
      if (defName in schemas) throw new Error(`$defs ${defName} of ${schema.$ref} collides with a component`);
      if (defName in hoisted && JSON.stringify(hoisted[defName]) !== JSON.stringify(linked)) {
        throw new Error(`$defs ${defName} differs between schema files: one name, one definition`);
      }
      hoisted[defName] = linked;
    }
    schemas[name] = relink(body);
  }
  Object.assign(schemas, hoisted);
  return doc;
}

const ast = await openapiTS(inlineDocument());
const body = astToString(ast).replace(/\r\n/g, '\n').replace(/\s+$/, '');
const text = `${HEADER}${body}\n`;

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(target);
  } catch {
    // an absent file is not current
  }
  if (current === null || !current.equals(Buffer.from(text, 'utf8'))) {
    console.error('contract.gen.ts is not current: run npm run contracts:types');
    process.exit(1);
  }
  console.log('contract types: current');
} else {
  writeFileSync(target, text, 'utf8');
  console.log('contract types: wrote frontend/src/lib/contract.gen.ts');
}
